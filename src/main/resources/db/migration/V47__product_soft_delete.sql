-- V47 — 주문 이력이 있는 상품도 관리자가 지울 수 있게 (2026-11-05 요청)
--
-- 주문 항목(order_item)이 상품을 가리키고 주문은 5년 보관이라 행 자체는 지우지 않는다.
-- 대신 지운 시각을 남기고, 관리자 목록 · 손님 화면 어디에도 보이지 않게 한다.
-- 주문 항목은 주문 당시 값(이름 · 사이즈 · 가격 · 사진)을 복사해 두었으므로 주문 내역은 그대로 보인다.
-- 남겨 두는 이유: 진행 중인 주문의 취소 · 교환 때 사이즈 재고를 되돌리고, 판매 통계가 상품별로 묶인다.
-- 주문 이력이 없는 상품은 지금처럼 행까지 지운다.
-- ============================================================

ALTER TABLE product ADD COLUMN deleted_at TIMESTAMPTZ;

COMMENT ON COLUMN product.deleted_at IS
    '관리자가 지운 시각. 주문 이력 때문에 행만 남긴 상품 — 관리자 목록 · 손님 화면에 나오지 않는다. 주소(slug)는 비워 둔다.';

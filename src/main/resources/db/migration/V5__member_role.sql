-- V5 — 회원 역할
--
-- 관리자 API(/api/admin/**)를 열기 위해 필요하다.
-- 그전까지는 모든 로그인 사용자가 같은 권한이었고, 관리자 기능이 없었으므로 문제가 없었다.
-- 상품 등록·이미지 업로드가 생기는 순간 "아무 회원이나 상품을 고칠 수 있는" 상태가 된다.
-- ============================================================

/*
 * 역할을 별도 테이블(member_role)이 아니라 컬럼으로 둔다.
 *
 * 한 사람이 여러 역할을 갖는 구조가 필요해지면 그때 테이블로 뺀다. 지금은
 * 손님이거나 운영자이거나 둘 중 하나고, 겸하는 경우가 없다. 미리 다대다로 만들면
 * 모든 조회에 조인이 하나씩 붙는데 그 값을 쓰는 곳은 인증 한 곳뿐이다.
 *
 * 기본값이 MEMBER 다. 새로 가입하는 사람이 관리자가 되는 일은 없어야 한다 —
 * 기본값을 '막힌 쪽'으로 두는 것이 이 스키마 전체의 규칙이다.
 */
ALTER TABLE member
    ADD COLUMN role TEXT NOT NULL DEFAULT 'MEMBER'
        CHECK (role IN ('MEMBER', 'ADMIN'));

COMMENT ON COLUMN member.role IS
    '기본 MEMBER. ADMIN 은 DB 에서 직접 부여한다 — 화면으로 승격하는 경로를 두지 않는다.';

/*
 * 관리자 계정을 여기서 만들지 않는다.
 *
 * 마이그레이션에 계정을 심으면 그 비밀번호가 저장소에 남는다. 모든 배포 환경이
 * 같은 값을 갖게 되고, 바꾸려면 또 마이그레이션이 필요하다.
 * 운영에서는 사람이 정상 가입한 뒤 아래 한 줄로 승격시킨다:
 *
 *   UPDATE member SET role = 'ADMIN' WHERE email = 'ops@leoneferito.com';
 *
 * 승격은 드물고 되돌리기 쉬우며, 기록이 DB 감사 로그에 남는다.
 */

-- 관리자는 소수다. 부분 인덱스라 MEMBER 행은 인덱스에 들어가지 않는다.
CREATE INDEX idx_member_admin ON member (email) WHERE role = 'ADMIN';

package com.leoneferito.member;

/**
 * 회원 상태.
 *
 * <p>잠금(로그인 실패 누적)은 여기 없다. 잠금은 <b>시간이 지나면 저절로 풀리는</b> 임시
 * 조건이라 상태가 아니라 {@code locked_until} 시각으로 둔다. 상태로 만들면 누군가
 * 풀어주는 절차가 따로 필요해지고, 그 절차를 잊으면 손님이 갇힌다.
 */
public enum MemberStatus {
    ACTIVE,

    /**
     * 이용 정지 (약관 제7조). 관리자가 걸고 관리자가 푼다. 로그인할 수 없다.
     * 잠금과 달리 시간이 지나도 풀리지 않는다.
     */
    SUSPENDED,

    /**
     * 탈퇴. 행을 지우지 않는다 — 주문 이력이 회원을 참조하게 되는데, 지우면 과거 주문의
     * 주인이 사라진다. 대신 개인정보를 전부 지운다({@link Member#withdraw}).
     * 로그인 처리에서는 없는 계정과 똑같이 취급한다.
     */
    WITHDRAWN
}
